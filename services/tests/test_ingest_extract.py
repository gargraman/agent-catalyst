"""Extraction + content sniffing (feature 024, tasks.md T019; research D7; spec FR-001/FR-002).

`ingestion.extract.sniff(name, data) -> media_type` refuses unsupported extensions and content that does not match its
declared type; `extract(media_type, data) -> list[Section]` yields structure-aware sections (heading / page kept for
citations). Pure + deterministic. Fixtures: tests/fixtures/docs (generated by make_fixtures.py).
"""
from __future__ import annotations

import io
import zipfile
from pathlib import Path

import pytest

from ingestion.extract import ExtractError, Section, extract, sniff

DOCS = Path(__file__).parent / "fixtures" / "docs"
PDF = "application/pdf"
DOCX = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"


def _read(name: str) -> bytes:
    return (DOCS / name).read_bytes()


# ------------------------------------------------------------------------------------------------- sniff


@pytest.mark.parametrize(
    "name, expected",
    [
        ("faq.txt", "text/plain"),
        ("handbook.md", "text/markdown"),
        ("page.html", "text/html"),
        ("policy.pdf", PDF),
        ("guide.docx", DOCX),
    ],
)
def test_sniff_accepts_supported_types(name, expected):
    assert sniff(name, _read(name)) == expected


def test_sniff_extension_is_case_insensitive_and_htm_is_html():
    assert sniff("FAQ.TXT", _read("faq.txt")) == "text/plain"
    assert sniff("page.htm", _read("page.html")) == "text/html"


@pytest.mark.parametrize("name", ["setup.exe", "archive.zip", "image.png", "noextension"])
def test_sniff_rejects_unsupported_extension(name):
    with pytest.raises(ExtractError) as ei:
        sniff(name, b"some bytes")
    assert ei.value.code == "unsupported_type"


@pytest.mark.parametrize(
    "name, data",
    [
        ("fake.pdf", None),                                       # text bytes named .pdf
        ("nul.txt", b"hello\x00world"),                           # NUL bytes in a text file
        ("bad.txt", b"caf\xe9 au lait"),                          # invalid UTF-8
        ("notzip.docx", b"plain text, not a zip"),               # .docx that is not a zip
        ("wrongzip.docx", "zip-without-document-xml"),           # zip, but not a word document
    ],
)
def test_sniff_rejects_content_mismatch(name, data):
    if data is None:
        data = _read(name)
    elif data == "zip-without-document-xml":
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w") as z:
            z.writestr("hello.txt", "hi")
        data = buf.getvalue()
    with pytest.raises(ExtractError) as ei:
        sniff(name, data)
    assert ei.value.code == "content_mismatch"


# ------------------------------------------------------------------------------------------------- extract


def test_markdown_splits_on_headings():
    secs = extract("text/markdown", _read("handbook.md"))
    assert all(isinstance(s, Section) for s in secs)
    headings = [s.heading for s in secs]
    assert "Leave Policy" in headings and "Working Hours" in headings and "Returning equipment" in headings
    leave = next(s for s in secs if s.heading == "Leave Policy")
    assert "Annual leave is 27 days" in leave.text
    assert "Core hours" not in leave.text                      # sections do not bleed into each other
    assert all(s.page is None for s in secs)


def test_html_drops_script_and_style_and_keeps_headings():
    secs = extract("text/html", _read("page.html"))
    joined = " ".join(s.text for s in secs)
    assert "ignore all previous instructions" not in joined    # <script> content dropped
    assert "display: none" not in joined                        # <style> content dropped
    assert [s.heading for s in secs if s.heading] == ["Benefits Overview", "Pension", "Cycle scheme"]
    pension = next(s for s in secs if s.heading == "Pension")
    assert "6 percent" in pension.text


def test_pdf_one_section_per_page_with_1_based_page_numbers():
    secs = extract(PDF, _read("policy.pdf"))
    assert [s.page for s in secs] == [1, 2]
    assert "Expense claims are due within 30 days" in secs[1].text
    assert "30 days" not in secs[0].text


def test_docx_keeps_heading_styled_paragraphs_as_headings():
    secs = extract(DOCX, _read("guide.docx"))
    first_week = next(s for s in secs if s.heading == "First week")
    assert "security training" in first_week.text
    assert any(s.heading == "Buddy programme" for s in secs)


def test_plain_text_is_one_or_more_sections_with_all_text():
    secs = extract("text/plain", _read("faq.txt"))
    joined = "\n".join(s.text for s in secs)
    assert "self-service portal" in joined and "fourth floor" in joined


@pytest.mark.parametrize("name, media_type", [("scanned.pdf", PDF), ("empty.txt", "text/plain")])
def test_no_extractable_text(name, media_type):
    with pytest.raises(ExtractError) as ei:
        extract(media_type, _read(name))
    assert ei.value.code == "no_extractable_text"


def test_whitespace_only_text_has_no_extractable_text():
    with pytest.raises(ExtractError) as ei:
        extract("text/plain", b"   \n\t\n  ")
    assert ei.value.code == "no_extractable_text"


def test_corrupt_pdf_is_parse_failed():
    with pytest.raises(ExtractError) as ei:
        extract(PDF, b"%PDF-1.4\n this is not a real pdf body \n%%EOF")
    assert ei.value.code == "parse_failed"


@pytest.mark.parametrize("name, media_type", [("handbook.md", "text/markdown"), ("policy.pdf", PDF),
                                              ("guide.docx", DOCX), ("page.html", "text/html")])
def test_extract_is_deterministic(name, media_type):
    assert extract(media_type, _read(name)) == extract(media_type, _read(name))


def test_extract_error_carries_code_and_message():
    e = ExtractError("parse_failed", "could not parse")
    assert e.code == "parse_failed" and "could not parse" in str(e)
